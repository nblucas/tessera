// Writes the contract's ABI to abi/TesseraLedger.ts, which is committed, so the backend's
// ledger adapter can import it without compiling this package. Run after any contract change;
// a test fails while the file is out of date.
import { mkdir, writeFile } from "node:fs/promises";
import hre from "hardhat";

export const ABI_FILE = "abi/TesseraLedger.ts";

const artifact = await hre.artifacts.readArtifact("TesseraLedger");
const source = `// Generated by \`npm run export-abi\`. Do not edit by hand.
export const tesseraLedgerAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

await mkdir("abi", { recursive: true });
await writeFile(ABI_FILE, source);
console.log(`Wrote ${ABI_FILE}`);
